import { z } from "zod";
import { DECADE_RANGES, RUNTIME_RANGES } from "./movies.js";

// Shared building blocks for request validation. Limits match the app's
// stores (BOARD_NAME_MAX, S_TIER_ORDER_MAX, MAX_PINNED, bio 140, …).

export const TIERS = ["S", "A", "B", "C", "D", "F"];
export const BOARD_NAME_MAX = 40;
// The order of your S tier (your favourites, #1 first) — as many as you
// have S films.
export const S_TIER_ORDER_MAX = 1000;
export const MAX_PINNED = 3;
export const BIO_MAX = 140;
export const MAX_RECENT_SEARCHES = 8;
export const MAX_PASSES = 300;

// A TMDB movie id, as a string ("603" is The Matrix).
export const movieId = z.string().regex(/^\d{1,10}$/, "Expected a TMDB movie id like 603");
export const tier = z.enum(TIERS);
export const timestamp = z.number().int().nonnegative();
// Board ids are made by the app (boardStore), so the server keeps them as-is.
export const boardId = z.string().regex(/^[A-Za-z0-9_-]{4,64}$/, "Invalid board id");
export const collectionId = z.string().trim().min(1).max(100);

export const handle = z
  .string()
  .trim()
  .transform((value) => value.replace(/^@/, ""))
  .pipe(
    z
      .string()
      .regex(/^[a-zA-Z0-9_.]{3,20}$/, "3–20 letters, numbers, dots or underscores"),
  );

export const preferences = z
  .object({
    genres: z.array(z.string().max(40)).max(30),
    minRating: z.number().min(0).max(10).nullable(),
    decade: z.enum(Object.keys(DECADE_RANGES)),
    runtime: z.enum(Object.keys(RUNTIME_RANGES)),
  })
  .partial();

export const DEFAULT_PREFERENCES = {
  genres: [],
  minRating: 7.0,
  decade: "Any",
  runtime: "Any",
};

// Taste DNA leanings from onboarding: one of -1 / 0 / 1 per dimension.
export const leanings = z
  .array(z.union([z.literal(-1), z.literal(0), z.literal(1)]))
  .length(6)
  .nullable();

// A challenge is generated by the app (utils/challenges.js); the backend
// only needs its id and target, and keeps the rest as-is.
export const challenge = z.looseObject({
  id: z.string().min(1).max(120),
  targetMovieId: movieId,
});

export const uniqueIds = (schema, max) =>
  z
    .array(schema)
    .max(max)
    .refine((ids) => new Set(ids).size === ids.length, "Ids must be unique");

export const pagination = {
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(250).default(50),
};
